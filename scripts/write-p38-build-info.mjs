#!/usr/bin/env node
/**
 * Gera carimbo de build (versão + código P38 + horário) para exibir na Home.
 */
import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const outPath = path.join(root, 'src/lib/p38BuildInfo.generated.js');
const pkgPath = path.join(root, 'package.json');

function readAppVersion() {
  try {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    return String(pkg.version || '0.0.0').trim();
  } catch {
    return '0.0.0';
  }
}

function resolveCommitSha() {
  const fromEnv = process.env.VERCEL_GIT_COMMIT_SHA || process.env.GITHUB_SHA;
  if (fromEnv && String(fromEnv).trim()) return String(fromEnv).trim();
  try {
    return execSync('git rev-parse HEAD', { encoding: 'utf8', cwd: root }).trim();
  } catch {
    return '';
  }
}

/** Ex.: `a1b2c3d` → `P38 A1B-2C3D` */
function formatBuildCode(sha) {
  const clean = String(sha || '').replace(/[^a-fA-F0-9]/g, '').toUpperCase();
  if (clean.length < 7) return 'P38 DEV-LOCAL';
  return `P38 ${clean.slice(0, 3)}-${clean.slice(3, 7)}`;
}

function formatBuildTime() {
  return new Intl.DateTimeFormat('pt-BR', {
    timeZone: 'America/Sao_Paulo',
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  })
    .format(new Date())
    .replace(',', '');
}

const sha = resolveCommitSha();
const code = formatBuildCode(sha);
const at = formatBuildTime();
const version = readAppVersion();

const content = `// AUTO-GENERATED by scripts/write-p38-build-info.mjs — não editar à mão

export const P38_APP_VERSION = ${JSON.stringify(version)};
export const P38_BUILD_STAMP_CODE = ${JSON.stringify(code)};
export const P38_BUILD_STAMP_AT = ${JSON.stringify(at)};
`;

fs.writeFileSync(outPath, content);
console.log(`[p38-build-info] v${version} · ${code} · ${at}`);
