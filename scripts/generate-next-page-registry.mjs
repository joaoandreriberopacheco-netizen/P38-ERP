#!/usr/bin/env node
/**
 * Gera registry de lazy loaders para o App Router Next.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const pagesDir = path.join(root, 'src/pages');

const names = fs
  .readdirSync(pagesDir)
  .filter((f) => f.endsWith('.jsx'))
  .map((f) => f.replace(/\.jsx$/, ''))
  .sort((a, b) => a.localeCompare(b));

const loaderEntries = names
  .map((name) => `  ${JSON.stringify(name)}: () => import('@/pages/${name}'),`)
  .join('\n');

const registryContent = `// AUTO-GENERATED by scripts/generate-next-page-registry.mjs — não editar à mão

export const P38_PAGE_LOADERS = {
${loaderEntries}
};

export const P38_PAGE_NAMES = ${JSON.stringify(names, null, 2)};

export const P38_MAIN_PAGE = 'Home';
`;

const namesContent = `// AUTO-GENERATED by scripts/generate-next-page-registry.mjs
export const P38_PAGE_NAMES = ${JSON.stringify(names, null, 2)};
export const P38_MAIN_PAGE = 'Home';
`;

fs.writeFileSync(path.join(root, 'src/next/pageRegistry.generated.js'), registryContent);
fs.writeFileSync(path.join(root, 'src/lib/p38PageNames.generated.js'), namesContent);

console.log(`[next-registry] ${names.length} páginas → src/next/pageRegistry.generated.js`);
